export interface CodeItem {
  code: string;
  reward: string;
  status: 'Active' | 'Expired';
  addedDate?: string;
}

export type AbilityTier = 'S+' | 'S' | 'A' | 'B';
export type AbilityRarity = 'Common' | 'Epic' | 'Legendary' | 'Mythical';

export interface AbilityItem {
  name: string;
  tier: AbilityTier;
  type: 'Defense' | 'Offense' | 'Mobility' | 'Utility';
  rarity: AbilityRarity;
  description: string;
  cooldown: string;
  /** In-game shop price, e.g. "7,500 Coins". Undefined for limited abilities. */
  price?: string;
  /** Numeric shop price in coins (for sorting). Undefined for limited abilities. */
  priceCoins?: number;
  /** Numeric cooldown in seconds (for sorting). Undefined when not documented. */
  cooldownSeconds?: number;
  availability: 'Purchasable' | 'Limited';
  obtainMethod: string;
}

export interface SwordInfoItem {
  name: string;
  status: 'Confirmed' | 'Unverified';
  source: string;
  notes: string;
}

